#!/usr/bin/env node
'use strict';

// PreToolUse hook: blocks edits to generated or vendored paths.
// Reads the hook JSON from stdin; exit 2 blocks the tool call.

const BLOCKED = [
  { re: /(^|\/)package-lock\.json$/, why: 'package-lock.json is generated by npm; do not edit it by hand' },
  { re: /(^|\/)node_modules(\/|$)/, why: 'node_modules is vendored; do not edit it' },
  { re: /(^|\/)test-results(\/|$)/, why: 'test-results is generated by Playwright; do not edit it' },
];

let data = '';
process.stdin.setEncoding('utf8');
process.stdin.on('data', (chunk) => { data += chunk; });
process.stdin.on('end', () => {
  let file = '';
  try {
    const payload = JSON.parse(data);
    file = String((payload.tool_input && payload.tool_input.file_path) || '');
  } catch (_) {
    process.exit(0);
  }
  const normalized = file.replace(/\\/g, '/');
  const hit = BLOCKED.find((b) => b.re.test(normalized));
  if (hit) {
    console.error('Blocked edit to ' + normalized + ': ' + hit.why + '.');
    process.exit(2);
  }
  process.exit(0);
});
process.stdin.on('error', () => process.exit(0));
